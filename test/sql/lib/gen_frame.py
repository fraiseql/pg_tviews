#!/usr/bin/env python3
"""Write the owner frame's settings into the tests' oracle, from its specification.

docs/reference/owner-frame.md is the specification of the frame every computation of a
TVIEW's rows runs in. The functions that read a backing view to judge a TVIEW
(`fresh_diff`, `gen_read_back`) take their SET clauses from it, not from pg_tviews'
constants (a unit test in src/owner.rs compares those with the specification):

    -- BEGIN frame            the search_path, render and plan settings
    -- BEGIN frame settings   the render and plan settings only
    ...
    -- END frame

Usage: gen_frame.py [--check] [file ...]   (default: the files below)
--check exits 1, naming the files, when a block differs from what it would write.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SPEC = ROOT / "docs/reference/owner-frame.md"
FILES = [
    ROOT / "test/sql/lib/assert_fresh.sql",
    ROOT / "test/sql/differential/gen/lib.sql",
]
GENERATED = (
    "-- generated by test/sql/lib/gen_frame.py from docs/reference/owner-frame.md"
)


def table(spec: str, heading: str) -> list[list[str]]:
    """The rows of the table under `## heading`, each cell without its backquotes."""
    lines = spec.splitlines()
    try:
        start = lines.index(f"## {heading}") + 1
    except ValueError:
        sys.exit(f"gen_frame: {SPEC.name} has no section {heading!r}")
    rows = []
    for line in lines[start:]:
        if line.startswith("## "):
            break
        if line.startswith("| `"):
            rows.append([c.strip().strip("`") for c in line.strip("|").split("|")])
    if not rows:
        sys.exit(f"gen_frame: {SPEC.name} has no table under {heading!r}")
    return rows


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def clauses(spec: str, with_search_path: bool) -> list[str]:
    settings = table(spec, "Render settings") + table(spec, "Plan settings")
    out = []
    if with_search_path:
        where = {row[0]: row[1] for row in table(spec, "Who and where")}
        out.append(f"SET search_path = {where['search_path']}")
    out += [f"SET {name} = {quote(value)}" for name, value in settings]
    return out


BLOCK = re.compile(
    r"^-- BEGIN frame( settings)?\n.*?^-- END frame$", re.MULTILINE | re.DOTALL
)


def render(text: str, spec: str) -> str:
    def block(m: re.Match[str]) -> str:
        head = "-- BEGIN frame" + (m.group(1) or "")
        body = clauses(spec, with_search_path=m.group(1) is None)
        return "\n".join([head, GENERATED, *body, "-- END frame"])

    return BLOCK.sub(block, text)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    files = [Path(a) for a in argv if a != "--check"] or FILES
    spec = SPEC.read_text()
    stale = []
    for path in files:
        text = path.read_text()
        if not BLOCK.search(text):
            sys.exit(f"gen_frame: {path} has no frame block")
        new = render(text, spec)
        if new != text:
            if check:
                stale.append(str(path))
            else:
                path.write_text(new)
    if stale:
        print(
            "gen_frame: the frame is not the specification's in: " + ", ".join(stale),
            "\n  run test/sql/lib/gen_frame.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

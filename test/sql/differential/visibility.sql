-- The visibility oracle: what each reader reads of a TVIEW is what the TVIEW's
-- definition returns to that reader. Loaded by gen/lib.sql; called by each check
-- of a generated case, as the session's superuser (gen_visible takes each reader's
-- role, which a SECURITY DEFINER function may not).
--
-- For each reader (gen_reader: tenant readers A and B, reader C who may not select
-- one column, reader N whom no policy lets read a row) and each TVIEW:
--
-- - The definition is evaluated as the reader: the backing view's query, run as a
--   query (a query has its caller's rights, so every base table's policies apply
--   to the reader, and each tv_* it reads is read with its own policies). A view's
--   rights are its owner's: this is ALTER VIEW … SET (security_invoker = true) on
--   the backing view, without the DDL. The generated chains have no other views.
--   Functions the definition calls run with their own rights (SECURITY DEFINER ones
--   as their owner): a limit of the oracle.
-- - A privilege error (42501) evaluating it means the reader reads none of its rows.
-- - Every row the reader reads from tv_<entity> must equal, binary-wise on every
--   column (data included), the row of the evaluation with the same key: a parent
--   embedding a row the reader may not read, or copying a column it may not
--   select, fails. A TVIEW reading rows of every tenant by construction (a lookup,
--   gen_shape.keys_only) is compared on its keys.
--
-- Raises LEAKED, naming the TVIEW, the reader and the keys.

-- The documented pattern on a generated TVIEW, as its creation leaves it: row
-- security on tv_<entity> with the base tables' tenant policy on its projected
-- tenant_id, and SELECT for each reader who may evaluate its definition. Self-test
-- 3 breaks it as gen.wrong says (gen/lib.sql).
CREATE FUNCTION gen_expose(tv regclass) RETURNS void LANGUAGE plpgsql AS $f$
DECLARE
    r record;
    wrong text := current_setting('gen.wrong');
BEGIN
    IF wrong <> 'nopolicy' THEN
        EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', tv);
        EXECUTE format('CREATE POLICY gen_tenant ON %s FOR SELECT TO %s '
                       'USING (tenant_id = nullif(current_setting(''gen.tenant'', true), '''')::int)',
                       tv, (SELECT string_agg(quote_ident(role), ', ' ORDER BY role)
                              FROM gen_reader WHERE role <> current_setting('gen.reader_n')));
    END IF;
    FOR r IN SELECT role, tenant FROM gen_reader ORDER BY role LOOP
        IF wrong = 'revoked' OR gen_evaluates(tv, r.role) THEN
            EXECUTE format('GRANT SELECT ON %s TO %I', tv, r.role);
        END IF;
    END LOOP;
END $f$;

-- The query of TVIEW `tv`'s backing view, as text.
CREATE FUNCTION gen_definition(tv regclass) RETURNS text LANGUAGE sql
SET search_path = pg_catalog, pg_temp AS $$
    SELECT rtrim(pg_get_viewdef(m.view_oid::oid), '; ' || chr(10))
      FROM tviews.pg_tview_meta m WHERE m.table_oid::oid = tv::oid
$$;

-- Whether `role` may evaluate the definition of `tv` (no privilege error).
CREATE FUNCTION gen_evaluates(tv regclass, role name) RETURNS boolean LANGUAGE plpgsql AS $f$
DECLARE def text := gen_definition(tv);
BEGIN
    PERFORM set_config('role', role, true);
    BEGIN
        -- The whole row: the planner drops output columns nothing reads, and with
        -- them the privilege checks of what they read.
        EXECUTE format('SELECT e FROM (%s) e LIMIT 0', def);
    EXCEPTION WHEN insufficient_privilege THEN
        PERFORM set_config('role', 'none', true);
        RETURN false;
    END;
    PERFORM set_config('role', 'none', true);
    RETURN true;
END $f$;

-- What `role` (of tenant `tenant`) reads of TVIEW `tv` that its evaluation of the
-- definition does not return, NULL when nothing.
CREATE FUNCTION gen_leak(tv regclass, key text, keys_only boolean, role name, tenant int)
RETURNS text LANGUAGE plpgsql
-- BEGIN frame
-- generated by test/sql/lib/gen_frame.py from docs/reference/owner-frame.md
SET search_path = pg_catalog, pg_temp
SET TimeZone = 'UTC'
SET DateStyle = 'ISO, YMD'
SET IntervalStyle = 'postgres'
SET extra_float_digits = '1'
SET bytea_output = 'hex'
SET lc_monetary = 'C'
SET lc_numeric = 'C'
SET lc_time = 'C'
SET timezone_abbreviations = 'Default'
SET array_nulls = 'on'
SET quote_all_identifiers = 'off'
SET transform_null_equals = 'off'
SET standard_conforming_strings = 'on'
SET xmlbinary = 'base64'
SET xmloption = 'content'
SET gin_fuzzy_search_limit = '0'
SET plan_cache_mode = 'auto'
SET jit = 'off'
SET row_security = 'on'
-- END frame
AS $f$
DECLARE
    v regclass;
    def text := public.gen_definition(tv);
    tv_cols text;
    caller text := pg_catalog.current_setting('role');
    n_read bigint;
    n_leaked bigint;
    keys text;
    evaluates boolean := true;
BEGIN
    SELECT m.view_oid::pg_catalog.oid::pg_catalog.regclass INTO v
      FROM tviews.pg_tview_meta m WHERE m.table_oid::pg_catalog.oid OPERATOR(pg_catalog.=) tv::pg_catalog.oid;
    -- The table's columns as the view's types, as fresh_diff reads them.
    SELECT pg_catalog.string_agg(pg_catalog.format('%1$I::%2$s AS %1$I', attname,
                                     pg_catalog.format_type(atttypid, atttypmod)), ', ' ORDER BY attnum)
      INTO tv_cols
      FROM pg_catalog.pg_attribute WHERE attrelid OPERATOR(pg_catalog.=) v AND attnum > 0 AND NOT attisdropped;
    PERFORM pg_catalog.set_config('role', role, true);
    PERFORM pg_catalog.set_config('gen.tenant', tenant::pg_catalog.text, true);
    BEGIN
        EXECUTE pg_catalog.format('SELECT pg_catalog.count(*) FROM %s', tv) INTO n_read;
    EXCEPTION WHEN insufficient_privilege THEN
        n_read := 0;
    END;
    IF n_read > 0 THEN
        BEGIN
            -- Every privilege the definition needs, checked on its whole row.
            EXECUTE pg_catalog.format('SELECT e FROM (%s) e LIMIT 0', def);
            EXECUTE pg_catalog.format(
                'SELECT pg_catalog.count(*), pg_catalog.string_agg(k, '','' ORDER BY k) '
                'FROM (SELECT a.%1$I::pg_catalog.text AS k FROM (SELECT %2$s FROM %3$s) a WHERE NOT EXISTS ('
                'SELECT 1 FROM (%4$s) b WHERE b.%1$I::pg_catalog.text OPERATOR(pg_catalog.=) a.%1$I::pg_catalog.text '
                'AND (%5$L OR a OPERATOR(pg_catalog.*=) b))) y',
                key, tv_cols, tv, def, keys_only) INTO n_leaked, keys;
        EXCEPTION WHEN insufficient_privilege THEN
            evaluates := false;
            EXECUTE pg_catalog.format('SELECT pg_catalog.count(*), pg_catalog.string_agg(%1$I::pg_catalog.text, '','' '
                                      'ORDER BY %1$I::pg_catalog.text) FROM %2$s', key, tv)
               INTO n_leaked, keys;
        END;
    END IF;
    PERFORM pg_catalog.set_config('role', caller, true);
    PERFORM pg_catalog.set_config('gen.tenant', '', true);
    IF coalesce(n_leaked, 0) = 0 THEN
        RETURN NULL;
    END IF;
    RETURN pg_catalog.format('%s read as %s (tenant %s): %s of its %s row(s) %s [%s]', tv, role, tenant,
        n_leaked, n_read,
        CASE WHEN evaluates THEN 'differ from its evaluation of the definition'
             ELSE 'are read while it may not evaluate the definition (42501)' END, keys);
END $f$;

-- Raise LEAKED unless every reader reads of every TVIEW only what its evaluation of
-- the definition returns.
CREATE FUNCTION gen_visible(label text) RETURNS void LANGUAGE plpgsql AS $f$
DECLARE
    r record;
    s record;
    leak text;
    failures text := '';
BEGIN
    FOR r IN SELECT role, tenant FROM gen_reader ORDER BY role LOOP
        FOR s IN SELECT tv, key, keys_only FROM gen_shape ORDER BY tv::text LOOP
            leak := gen_leak(s.tv, s.key, s.keys_only, r.role, r.tenant);
            IF leak IS NOT NULL THEN
                failures := failures || E'\n  ' || leak;
            END IF;
        END LOOP;
    END LOOP;
    IF failures <> '' THEN
        RAISE EXCEPTION 'LEAKED after %:%', label, failures;
    END IF;
END $f$;

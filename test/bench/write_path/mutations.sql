SELECT tviews.pg_tviews_create('mb.tv_location', $$
  SELECT pk_location, id, jsonb_build_object('identifier', identifier, 'name', name,
    'address', jsonb_build_object('street', street, 'city', city, 'zip', zip, 'country', country,
                                  'floor', floor, 'room', room, 'building', building),
    'contact', jsonb_build_object('phone', phone, 'email', email),
    'notes', notes, 'code', code, 'kind', kind,
    'events', (SELECT count(*) FROM mb.tb_event e WHERE e.fk_location = l.pk_location)) AS data
  FROM mb.tb_location l $$);
SELECT tviews.pg_tviews_create('mb.tv_machine', $$
  SELECT pk_machine, id, jsonb_build_object('name', name, 'model', model, 'serial', serial) AS data
  FROM mb.tb_machine $$);
SELECT tviews.pg_tviews_create('mb.tv_allocation', $$
  SELECT a.pk_allocation, a.id, a.fk_location, a.fk_machine,
         jsonb_build_object('started', a.started, 'note', a.note,
                            'location', l.data, 'machine', m.data) AS data
  FROM mb.tb_allocation a
  JOIN mb.tv_location l ON l.pk_location = a.fk_location
  JOIN mb.tv_machine m ON m.pk_machine = a.fk_machine $$);

-- update_location: 13 single-field UPDATEs of one row (per statement).
CREATE FUNCTION update_location_per_statement(p int) RETURNS jsonb LANGUAGE plpgsql AS $$
BEGIN
  UPDATE mb.tb_location SET name = name || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET street = street || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET city = city || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET zip = zip || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET country = country || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET floor = floor || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET room = room || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET building = building || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET phone = phone || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET email = email || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET notes = left(notes, 150) || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET code = code || '.' WHERE pk_location = p;
  UPDATE mb.tb_location SET kind = kind || '.' WHERE pk_location = p;
  RETURN (SELECT data FROM mb.tv_location WHERE pk_location = p);
END $$;
-- The same change written once.
CREATE FUNCTION update_location_once(p int) RETURNS jsonb LANGUAGE plpgsql AS $$
BEGIN
  UPDATE mb.tb_location SET name = name || '.', street = street || '.', city = city || '.',
         zip = zip || '.', country = country || '.', floor = floor || '.', room = room || '.',
         building = building || '.', phone = phone || '.', email = email || '.',
         notes = left(notes, 150) || '.', code = code || '.', kind = kind || '.'
   WHERE pk_location = p;
  RETURN (SELECT data FROM mb.tv_location WHERE pk_location = p);
END $$;
-- create: INSERT, then an UPDATE of the same row (its identifier).
CREATE FUNCTION create_location_per_statement() RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v int;
BEGIN
  INSERT INTO mb.tb_location (name, city, kind) VALUES ('new', 'City', 'site') RETURNING pk_location INTO v;
  UPDATE mb.tb_location SET identifier = 'loc-' || v WHERE pk_location = v;
  RETURN (SELECT data FROM mb.tv_location WHERE pk_location = v);
END $$;
CREATE FUNCTION create_location_once() RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE v int := nextval(pg_get_serial_sequence('mb.tb_location', 'pk_location'));
BEGIN
  INSERT INTO mb.tb_location (pk_location, identifier, name, city, kind)
  VALUES (v, 'loc-' || v, 'new', 'City', 'site');
  RETURN (SELECT data FROM mb.tv_location WHERE pk_location = v);
END $$;
-- loop: 10 child INSERTs touching one parent (its event count).
CREATE FUNCTION log_events_per_statement(p int) RETURNS jsonb LANGUAGE plpgsql AS $$
BEGIN
  FOR i IN 1..10 LOOP
    INSERT INTO mb.tb_event (fk_location, kind) VALUES (p, 'k' || i);
  END LOOP;
  RETURN (SELECT data FROM mb.tv_location WHERE pk_location = p);
END $$;
CREATE FUNCTION log_events_once(p int) RETURNS jsonb LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO mb.tb_event (fk_location, kind) SELECT p, 'k' || i FROM generate_series(1, 10) i;
  RETURN (SELECT data FROM mb.tv_location WHERE pk_location = p);
END $$;

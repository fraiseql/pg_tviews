-- Schema of test/bench/write_path/mutations.sh: a printoptim-shaped model. A large
-- embedding TVIEW (tv_allocation) holds the documents of the location and machine
-- it allocates; mutation functions write the way fraiseql's do, called as one
-- outer SELECT.
SET client_min_messages TO WARNING;
CREATE EXTENSION IF NOT EXISTS pg_tviews CASCADE;
DROP SCHEMA IF EXISTS mb CASCADE;
CREATE SCHEMA mb;
SET search_path = mb, public;

CREATE TABLE tb_location (pk_location int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id uuid NOT NULL DEFAULT gen_random_uuid(), identifier text, name text, street text,
  city text, zip text, country text, floor text, room text, building text, phone text,
  email text, notes text, code text, kind text);
CREATE TABLE tb_machine (pk_machine int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id uuid NOT NULL DEFAULT gen_random_uuid(), name text, model text, serial text);
CREATE TABLE tb_allocation (pk_allocation int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  fk_location int NOT NULL REFERENCES tb_location, fk_machine int NOT NULL REFERENCES tb_machine,
  started date, note text);
CREATE INDEX ON tb_allocation (fk_location);
CREATE INDEX ON tb_allocation (fk_machine);
CREATE TABLE tb_event (pk_event int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id uuid NOT NULL DEFAULT gen_random_uuid(), fk_location int NOT NULL REFERENCES tb_location,
  kind text, at timestamptz NOT NULL DEFAULT now());
CREATE INDEX ON tb_event (fk_location);


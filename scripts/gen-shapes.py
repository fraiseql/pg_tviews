#!/usr/bin/env python3
"""Generate the shape tables of docs/reference/shapes.md from docs/reference/dialect.toml.

Every [[production]] of dialect.toml becomes one row of its axis's table, between the
markers in shapes.md. The entries are checked first: unique ids, a known axis, a
SQLSTATE of five characters, and evidence that exists (each regression test under
test/sql/regress/, each TVIEW in test/sql/differential/schema.sql, each source file).

Usage: scripts/gen-shapes.py          rewrite shapes.md
       scripts/gen-shapes.py --check  exit 1 when shapes.md differs from what it writes
"""

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOML = ROOT / "docs/reference/dialect.toml"
SHAPES = ROOT / "docs/reference/shapes.md"
REGRESS = ROOT / "test/sql/regress"
DIFFERENTIAL = ROOT / "test/sql/differential/schema.sql"
BEGIN = "<!-- BEGIN dialect.toml: generated by scripts/gen-shapes.py, do not edit -->"
END = "<!-- END dialect.toml -->"
AXES = {
    "A": "Statement and output",
    "B": "Relations read",
    "C": "How a column is read",
    "D": "What a value depends on besides rows",
    "E": "Time",
    "F": "Declared staleness",
}
REQUIRED = ("id", "axis", "shape", "example", "maintained")


def problems(productions: list[dict]) -> list[str]:
    """What is wrong with the entries, one line each."""
    out = []
    differential = set(
        re.findall(r"harness_create\('(tv_\w+)'", DIFFERENTIAL.read_text())
    )
    seen: set[str] = set()
    for p in productions:
        pid = p.get("id", "?")
        out += [f"{pid}: no {k}" for k in REQUIRED if k not in p]
        if pid in seen:
            out.append(f"{pid}: listed twice")
        seen.add(pid)
        if p.get("axis") not in AXES:
            out.append(f"{pid}: axis {p.get('axis')!r} is not one of {''.join(AXES)}")
        state = p.get("sqlstate")
        if state is not None and not re.fullmatch(r"[0-9A-Z]{5}", state):
            out.append(f"{pid}: sqlstate {state!r}")
        if not (p.get("tests") or p.get("differential") or p.get("evidence")):
            out.append(f"{pid}: no evidence (tests, differential or evidence)")
        out += [
            f"{pid}: no test {t}"
            for t in p.get("tests", [])
            if not (REGRESS / t).is_file()
        ]
        out += [
            f"{pid}: no TVIEW {t} in the differential schema"
            for t in p.get("differential", [])
            if t not in differential
        ]
        out += [
            f"{pid}: no file {w}"
            for w in p.get("walker", [])
            if not (ROOT / w).is_file()
        ]
    return out


def maintained(p: dict) -> str:
    text = p["maintained"]
    state = p.get("sqlstate")
    return f"{text} (`{state}`)" if state and f"`{state}`" not in text else text


def evidence(p: dict) -> str:
    parts = [f"`{t}`" for t in p.get("tests", [])]
    if p.get("differential"):
        parts.append("differential " + ", ".join(f"`{t}`" for t in p["differential"]))
    if p.get("evidence"):
        parts.append(p["evidence"])
    return "; ".join(parts)


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def tables(productions: list[dict]) -> str:
    lines = [BEGIN]
    for axis, title in AXES.items():
        rows = [p for p in productions if p["axis"] == axis]
        if not rows:
            continue
        lines += ["", f"### {axis}. {title}", ""]
        lines += ["| Shape | Example | Maintained | Evidence |", "|---|---|---|---|"]
        lines += [
            "| "
            + " | ".join(
                cell(c) for c in (p["shape"], p["example"], maintained(p), evidence(p))
            )
            + " |"
            for p in rows
        ]
    lines += ["", END]
    return "\n".join(lines)


def main() -> None:
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit(__doc__)
    productions = tomllib.loads(TOML.read_text()).get("production", [])
    wrong = problems(productions)
    if wrong:
        sys.exit("dialect.toml:\n  " + "\n  ".join(wrong))
    current = SHAPES.read_text()
    start, end = current.find(BEGIN), current.find(END)
    if start < 0 or end < start:
        sys.exit(f"{SHAPES.relative_to(ROOT)}: the markers are missing")
    wanted = current[:start] + tables(productions) + current[end + len(END) :]
    if check:
        if wanted != current:
            sys.exit(
                f"{SHAPES.relative_to(ROOT)} differs from dialect.toml: run scripts/gen-shapes.py"
            )
        return
    SHAPES.write_text(wanted)


if __name__ == "__main__":
    main()
